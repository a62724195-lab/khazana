const { contextBridge, ipcRenderer, webUtils } = require('electron');
const inv = (c, ...a) => ipcRenderer.invoke(c, ...a);

contextBridge.exposeInMainWorld('api', {
  pathForFile: f => { try { return webUtils.getPathForFile(f); } catch (e) { return ''; } },
  load: () => inv('vault:load'),
  save: items => inv('vault:save', items),
  inspect: p => inv('file:inspect', p),
  makeThumb: (p, k) => inv('thumb:make', p, k),
  pick: o => inv('pick', o),
  alertUser: () => inv('app:alert'),
  open: p => inv('item:open', p),
  reveal: p => inv('item:reveal', p),
  openUrl: u => inv('item:openUrl', u),
  exists: paths => inv('items:exists', paths),
  aiSuggest: d => inv('ai:suggest', d),
  aiSearch: d => inv('ai:search', d),
  aiFill: d => inv('ai:fill', d),
  hasKey: () => inv('key:has'),
  setKey: k => inv('key:set', k),
  scanApps: () => inv('apps:scan'),
  exportBackup: () => inv('backup:export'),
  importBackup: () => inv('backup:import'),
  dataPath: () => inv('data:path'),
  fenceToggle: s => inv('fence:toggle', s),
  fenceList: () => inv('fence:list'),
  fenceClose: () => inv('fence:close'),
  fenceCollapse: on => inv('fence:collapse', on),
  fenceResize: (w, h, done) => inv('fence:resize', w, h, done),
  openMain: () => inv('fence:main'),
  extAdd: (p, s) => inv('ext:add', p, s),
  updateCheck: () => inv('update:check'),
  updateApply: () => inv('update:apply'),
  playGet: () => inv('play:get'),
  backupNow: () => inv('backup:now'),
  backupOpen: () => inv('backup:open'),
  backupChoose: () => inv('backup:choose'),
  extRun: g => inv('ext:run', g),
  extOpen: (id, show) => inv('ext:open', id, show),
  quickHide: () => inv('quick:hide'),
  quickSize: h => inv('quick:size', h),
  onExt: cb => ipcRenderer.on('ext', (_e, d) => cb(d)),
  onQuickReset: cb => ipcRenderer.on('quick:reset', () => cb()),
  onFocusSearch: cb => ipcRenderer.on('focus-search', () => cb())
});
